#!/usr/bin/env node
// POST /auth/login isteğinin "Tests" event'ine auto-token JavaScript'ini ekler.
// openapi-to-postmanv2 native event üretmediği için kolajları biz yapıyoruz.
//
// Kullanım: node scripts/inject-postman-auth.mjs <collection.json>

import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('Usage: inject-postman-auth.mjs <collection.json>');
  process.exit(1);
}

const collection = JSON.parse(readFileSync(file, 'utf8'));

const TESTS_SCRIPT = [
  '// Auto-saves token + user + refresh into the environment so subsequent',
  '// requests authenticate automatically. Generated by inject-postman-auth.mjs.',
  'try {',
  '    const body = pm.response.json();',
  '    const data = body && body.data ? body.data : body;',
  '    if (data && data.accessToken) {',
  '        pm.environment.set("accessToken", data.accessToken);',
  '    }',
  '    if (data && data.refreshToken) {',
  '        pm.environment.set("refreshToken", data.refreshToken);',
  '    }',
  '    if (data && data.user && data.user.id) {',
  '        pm.environment.set("userId", data.user.id);',
  '    }',
  '} catch (e) {',
  '    console.warn("Auth inject script could not parse response", e);',
  '}',
];

let patched = 0;

const visit = (items) => {
  for (const item of items ?? []) {
    if (Array.isArray(item.item)) {
      visit(item.item);
      continue;
    }
    const url = item.request?.url;
    const path = Array.isArray(url?.path) ? url.path.join('/') : '';
    const method = (item.request?.method ?? '').toUpperCase();
    const isLogin = method === 'POST' && /(^|\/)auth\/login$/.test(path);
    const isRefresh = method === 'POST' && /(^|\/)auth\/refresh$/.test(path);
    if (!isLogin && !isRefresh) continue;

    item.event = item.event ?? [];
    // Existing test listener varsa override et (idempotent)
    item.event = item.event.filter((e) => e.listen !== 'test');
    item.event.push({
      listen: 'test',
      script: { type: 'text/javascript', exec: TESTS_SCRIPT },
    });
    patched += 1;
  }
};

visit(collection.item);

writeFileSync(file, `${JSON.stringify(collection, null, 2)}\n`, 'utf8');
console.log(`[inject-postman-auth] patched ${patched} request(s) with auto-token script`);
